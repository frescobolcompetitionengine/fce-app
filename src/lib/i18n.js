function replaceParams(template, params = {}) {
  if (typeof template !== 'string') return template;
  return template.replace(/\{(\w+)\}/g, (_, key) => (params[key] ?? `{${key}}`));
}

function ensureTrailingPeriod(text, key) {
  if (typeof text !== 'string') return text;
  const value = text.trim();
  if (!value) return value;
  if (NO_PERIOD_KEYS.has(key)) return value;
  if (/[.!?…:]$/.test(value)) return value;
  return `${value}.`;
}

function readStoredLanguage() {
  if (typeof window === 'undefined') return null;
  const sessionLanguage = window.sessionStorage.getItem(LANGUAGE_KEY);
  if (sessionLanguage) return sessionLanguage;

  const legacyLanguage = window.localStorage.getItem(LEGACY_LANGUAGE_KEY);
  if (legacyLanguage) {
    window.sessionStorage.setItem(LANGUAGE_KEY, legacyLanguage);
    window.localStorage.removeItem(LEGACY_LANGUAGE_KEY);
  }
  return legacyLanguage || null;
}

function persistStoredLanguage(language) {
  if (typeof window === 'undefined') return;
  window.sessionStorage.setItem(LANGUAGE_KEY, language);
}

export function getAppLanguage(preferredLanguage = null) {
  return preferredLanguage || readStoredLanguage() || DEFAULT_LANGUAGE;
}

export function setAppLanguage(language) {
  persistStoredLanguage(language);
  window.dispatchEvent(new CustomEvent('app-language-changed', { detail: language }));
}

export function useI18n() {
  const { appPublicSettings, isLoadingPublicSettings } = useAuth();
  const [language, setLanguage] = useState(() => getAppLanguage(appPublicSettings?.language));

  useEffect(() => {
    const onStorage = () => setLanguage(getAppLanguage(appPublicSettings?.language));
    const onCustom = (event) => setLanguage(event.detail || getAppLanguage());
    window.addEventListener('storage', onStorage);
    window.addEventListener('app-language-changed', onCustom);
    return () => {
      window.removeEventListener('storage', onStorage);
      window.removeEventListener('app-language-changed', onCustom);
    };
  }, [appPublicSettings?.language]);

  useEffect(() => {
    if (isLoadingPublicSettings) return;
    const nextLanguage = getAppLanguage(appPublicSettings?.language);
    if (nextLanguage !== language) {
      setLanguage(nextLanguage);
    }
  }, [appPublicSettings?.language, isLoadingPublicSettings, language]);

  const t = (key, params) => {
    const dict = messages[language] && Object.keys(messages[language]).length > 0 ? messages[language] : messages[DEFAULT_LANGUAGE];
    const template = dict[key] || messages[DEFAULT_LANGUAGE][key] || key;
    return ensureTrailingPeriod(replaceParams(template, params), key);
  };

  return { language, setLanguage: setAppLanguage, t };
}
